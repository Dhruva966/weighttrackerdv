/** Resolve a catalog slug to a verified local PDF icon filename slug. */
export function resolvePdfIconSlug(slug: string, equipment?: EquipmentKind): string | undefined {
  if (PDF_ICON_SLUGS.has(slug)) {
    return slug;
  }

  const alias = PDF_ICON_ALIASES[slug];
  if (alias && PDF_ICON_SLUGS.has(alias)) {
    return alias;
  }

  if (equipment) {
    const withEquipment = `${slug}-${equipment}`;
    if (PDF_ICON_SLUGS.has(withEquipment)) {
      return withEquipment;
    }
  }

  return undefined;
}

/** Local `/exercise-icons/<slug>.jpg` when a verified PDF diagram crop exists. */
export function pdfIconUrl(slug: string, equipment?: EquipmentKind): string | undefined {
  const resolved = resolvePdfIconSlug(slug, equipment);
  return resolved ? `/exercise-icons/${resolved}.jpg` : undefined;
}
